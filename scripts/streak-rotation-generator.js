#!/usr/bin/env node
/**
 * Generate daily streak rotation metadata (date seed, anti-repeat window, week link).
 *
 * Usage:
 *   node scripts/streak-rotation-generator.js [--date YYYY-MM-DD]
 *
 * Writes src/data/streak_rotation.js — consumed by client streak-rotation module.
 * AB selection at play time uses pickStreakAbFromPool(streakIndex) with this date seed.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { getIsoWeekKey, getMondayDateString } from '../src/js/challenge-utils.js';
import { dateToSeed, mulberry32 } from '../src/js/lib/streak-ab-scorer.js';
import { STREAK_POOL_META, STREAK_POOL_ABS } from '../src/data/streak_pool.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = path.resolve(__dirname, '../src/data/streak_rotation.js');

const args = process.argv.slice(2);
const dateIdx = args.indexOf('--date');
const anchor = dateIdx !== -1 ? new Date(`${args[dateIdx + 1]}T12:00:00Z`) : new Date();
const dateKey = anchor.toISOString().slice(0, 10);
const weekId = getIsoWeekKey(anchor);

function buildDailyOrder(pool, seed) {
  const rng = mulberry32(seed);
  const copy = [...pool];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy.map((ab) => ab.id);
}

function main() {
  const eligible = STREAK_POOL_ABS.filter((ab) => ab.eligible);
  const seed = dateToSeed(dateKey);
  const dailyOrder = buildDailyOrder(eligible, seed);

  const meta = {
    version: 1,
    generatedAt: new Date().toISOString(),
    rotationDate: dateKey,
    weekId,
    weekResetDate: getMondayDateString(anchor),
    poolVersion: STREAK_POOL_META.builtAt,
    poolTotalAbs: STREAK_POOL_META.totalAbs,
    shuffleSeed: seed,
    maxDaysBeforeReuse: 7,
    /** Ordered AB ids for today's deck (all eligible ABs shuffled once per day). */
    dailyOrder,
  };

  console.log(`Streak rotation for ${dateKey} (week ${weekId}):`);
  console.log(`  Pool size: ${eligible.length}`);
  console.log(`  Daily order: ${dailyOrder.length} ABs`);

  const js = `/**
 * Streak Challenge daily rotation — generated by scripts/streak-rotation-generator.js
 * Regenerated daily via GitHub Actions (UTC midnight) or manually.
 */
export const STREAK_ROTATION_META = ${JSON.stringify(meta, null, 2)};
`;

  fs.writeFileSync(OUTPUT_PATH, js, 'utf-8');
  console.log(`Written: ${OUTPUT_PATH}`);
}

main();
